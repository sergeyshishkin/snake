// ============================================================
// [FILE: cookie.js]
// Назначение: управление cookie-баннером и гейт запуска игры
// Правится: при смене текста баннера, политики cookies
// Зависит: ни от чего (получает колбэк извне)
// Экспортирует: createCookieGate
// ============================================================


// ============================================================
// [BLOCK: constants]
// ============================================================

// Ключ localStorage, под которым хранится факт согласия.
// Меняйте только при смене текста/политики, чтобы заставить
// всех пользователей подтвердить согласие заново.
const COOKIE_ACCEPT_KEY = 'sushi_snake_cookie_accepted_v1';

// Задержка анимации скрытия (в мс). Должна совпадать
// с transition в cookie.css.
const HIDE_ANIMATION_MS = 350;


// ============================================================
// [BLOCK: create-cookie-gate]
// Возвращает объект с методами управления гейтом.
//
// @param {Object} options
// @param {Function} options.onAccept — что делать после согласия
//                                     (обычно — разблокировать игру)
// ============================================================
export function createCookieGate({ onAccept }) {

  // ----------------------------------------------------------
  // DOM-элементы баннера
  // ----------------------------------------------------------
  const banner     = document.getElementById('cookieBanner');
  const acceptBtn  = document.getElementById('cookieAccept');

  // ----------------------------------------------------------
  // Проверяем, согласился ли пользователь ранее.
  // Обёрнуто в try/catch — в приватном режиме localStorage
  // может бросать исключения.
  // ----------------------------------------------------------
  let alreadyAccepted = false;
  try {
    alreadyAccepted = localStorage.getItem(COOKIE_ACCEPT_KEY) === '1';
  } catch (e) {
    // localStorage недоступен — считаем, что не соглашался
    alreadyAccepted = false;
  }


  // ==========================================================
  // [BLOCK: hide-banner]
  // Плавно прячет баннер через класс .hidden (см. cookie.css).
  // Через HIDE_ANIMATION_MS полностью убирает из потока.
  // ==========================================================
  function hideBanner() {
    banner.classList.add('hidden');
    setTimeout(() => {
      banner.style.display = 'none';
    }, HIDE_ANIMATION_MS);
  }


  // ==========================================================
  // [BLOCK: accept]
  // Обработчик клика по кнопке «同意 / ACCEPT».
  //   1. Сохраняет согласие в localStorage
  //   2. Прячет баннер
  //   3. Вызывает onAccept() — разблокирует игру
  // ==========================================================
  function accept() {
    try {
      localStorage.setItem(COOKIE_ACCEPT_KEY, '1');
    } catch (e) {
      // приватный режим — не критично, просто не запомнится
    }

    hideBanner();
    onAccept();
  }


  // ==========================================================
  // [BLOCK: init]
  // Запуск модуля.
  // Если пользователь уже соглашался ранее — баннер не показываем,
  // сразу вызываем onAccept().
  // Иначе — вешаем обработчик на кнопку и ждём.
  // ==========================================================
  function init() {
    if (alreadyAccepted) {
      // Скрываем мгновенно, без анимации
      banner.style.display = 'none';
      onAccept();
      return;
    }

    // Ждём клика по кнопке
    acceptBtn.addEventListener('click', accept);
  }


  // ==========================================================
  // [BLOCK: public-api]
  // ==========================================================
  return {
    init,
    accept,                       // на случай ручного вызова
    isAccepted: () => alreadyAccepted,
  };
}